_PIXELS = {
    char: tuple(
        (x, y)
        for y, row in enumerate(rows.split())
        for x in range(11)
        if int(row, 16) & (0x8000 >> x)
    )
    for char, rows in _ROWS.items()
}


def text_width(label: str) -> int:
    return sum(4 if char.isascii() else 11 for char in label)


def draw_text(screen, x: int, y: int, label: str, color: int) -> None:
    for char in label:
        if char.isascii():
            screen.text(x, y + 4, char, color)
            x += 4
        else:
            for dx, dy in _PIXELS[char]:
                screen.pset(x + dx, y + dy, color)
            x += 11
